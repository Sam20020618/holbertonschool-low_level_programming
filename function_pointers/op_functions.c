#include "calc.h"

/**
 * op_add - Adds a and b togther
 * @a: The first number
 * @b: The second number
 *
 * Return: a + b
 */

int op_add(int a, int b)
{
return (a + b);
}

/**
 * op_sub - Subs a and b togther
 * @a: The first number
 * @b: The second number
 * Return: a - b
 */

int op_sub(int a, int b)
{
return (a - b);
}

/**
 * op_mul - Times a and b togther
 * @a: The first number
 * @b: The second number
 *
 * Return: a * b
 */
int op_mul(int a, int b)
{
return (a * b);
}

/**
 * op_div - Divdie a and b togther
 * @a: The first number
 * @b: The second number
 * Return: a / b
 */
int op_div(int a, int b)
{
return (a / b);
}

/**
 * op_mod - The remainder of a and b togther
 * @a: The first number
 * @b: The second number
 * Return: a % b
*/
int op_mod(int a, int b)
{
return (a % b);
}
